#!/usr/bin/env bash
# Concatenates every migration, in order, into supabase/setup.sql: one file to paste into the
# Supabase SQL Editor on a fresh project. Run again whenever a migration is added.
set -euo pipefail
cd "$(dirname "$0")/.."
out=supabase/setup.sql
{
  echo "-- six-month-plan: full schema for a fresh Supabase project."
  echo "-- Generated by scripts/build-setup-sql.sh from supabase/migrations/*.sql ($(ls supabase/migrations/*.sql | wc -l | tr -d ' ') files)."
  echo "-- Paste the whole file into Supabase → SQL Editor and run it once. For an existing project,"
  echo "-- run only the migrations you haven't yet (each is safe to run again)."
  echo "-- Reminders/digests cron is separate: supabase/cron.sql."
  echo
  for f in $(ls supabase/migrations/*.sql | sort); do
    echo "-- ======================================================================"
    echo "-- $(basename "$f")"
    echo "-- ======================================================================"
    cat "$f"
    echo
  done
} > "$out"
echo "wrote $out ($(wc -l < "$out" | tr -d ' ') lines)"
