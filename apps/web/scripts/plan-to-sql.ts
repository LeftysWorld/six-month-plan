/**
 * Turn an export of the app's data (my-plan.json, or Settings → Export) into one SQL file you can
 * paste into Supabase → SQL Editor, owned by your user.
 *
 *   npx tsx apps/web/scripts/plan-to-sql.ts --user YOUR-USER-UUID [--in my-plan.json] [--wipe] > my-plan.sql
 *
 * --user  your auth user id (Supabase → Authentication → Users → the UUID next to your email).
 *         The SQL Editor runs as postgres, where auth.uid() is null, so the owner has to be spelled out.
 * --wipe  start the file by deleting everything that user already has (the app's Import does the same).
 *
 * The simpler route is the app itself: sign in, Settings → Import, pick my-plan.json. This script is
 * for when you'd rather see the rows, keep the SQL, or load without the browser.
 */
import { readFileSync } from 'node:fs';

const args = process.argv.slice(2);
const opt = (name: string): string | null => {
  const i = args.indexOf(`--${name}`);
  return i >= 0 ? (args[i + 1] ?? '') : null;
};
const user = opt('user');
const file = opt('in') ?? 'my-plan.json';
const wipe = args.includes('--wipe');
if (!user || !/^[0-9a-f-]{36}$/i.test(user)) {
  console.error('Pass --user <uuid>: Supabase → Authentication → Users → your row → copy the UUID.');
  process.exit(1);
}

type Row = Record<string, unknown>;
const data = JSON.parse(readFileSync(file, 'utf8')) as Record<string, unknown> & { profile: Row };

/** App collection → table, in insert order (parents before children). */
const ORDER: [string, string][] = [
  ['plans', 'plans'],
  ['paths', 'paths'],
  ['experiments', 'path_experiments'],
  ['groups', 'goal_groups'],
  ['goals', 'goals'],
  ['measurementTypes', 'measurement_types'],
  ['planGoals', 'plan_goals'],
  ['goalTargets', 'goal_targets'],
  ['planSteps', 'plan_steps'],
  ['milestones', 'milestones'],
  ['actions', 'actions'],
  ['actionGoals', 'action_goals'],
  ['schedules', 'action_schedules'],
  ['sessions', 'sessions'],
  ['workoutSets', 'workout_sets'],
  ['measurements', 'measurements'],
  ['weekPlans', 'week_plans'],
  ['reviews', 'reviews'],
  ['changeLog', 'change_log'],
  ['ideas', 'goal_ideas'],
];
/** Columns stored as jsonb (every other array is a Postgres array). */
const JSONB: Record<string, Set<string>> = {
  paths: new Set(['years', 'gauges', 'gauge_log', 'questions', 'notes']),
  actions: new Set(['workout_plan']),
  reviews: new Set(['goal_results', 'goal_decisions']),
  change_log: new Set(['old_value', 'new_value']),
};
/** Columns older exports carry that the schema no longer has. */
const GONE: Record<string, Set<string>> = {
  goals: new Set(['after_goal_id']),
  goal_ideas: new Set(['prep', 'selected_at']),
  goal_groups: new Set(['outcome']),
};
/** Attachments point at files in storage that the SQL can't carry; they're left out. */

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
function literal(table: string, col: string, v: unknown): string {
  if (v === null || v === undefined) return 'null';
  if (JSONB[table]?.has(col)) return `${q(JSON.stringify(v))}::jsonb`;
  if (typeof v === 'number') return Number.isFinite(v) ? String(v) : 'null';
  if (typeof v === 'boolean') return v ? 'true' : 'false';
  if (Array.isArray(v)) return `array[${v.map((x) => (typeof x === 'number' ? String(x) : q(String(x)))).join(', ')}]${v.length === 0 ? (col === 'obstacles' ? '::text[]' : '::int[]') : ''}`;
  if (typeof v === 'object') return `${q(JSON.stringify(v))}::jsonb`;
  return q(String(v));
}

const out: string[] = [];
out.push('-- Generated by apps/web/scripts/plan-to-sql.ts. Paste into Supabase → SQL Editor and run once.');
out.push(`-- Owner: ${user}`);
out.push('begin;');
if (wipe) {
  const tables = ['attachments', 'goal_ideas', 'change_log', 'reviews', 'week_plans', 'measurements', 'workout_sets', 'sessions', 'path_experiments', 'action_goals', 'action_schedules', 'actions', 'milestones', 'goal_targets', 'plan_steps', 'plan_goals', 'goals', 'goal_groups', 'plans', 'paths', 'measurement_types', 'push_subscriptions'];
  for (const t of tables) out.push(`delete from public.${t} where user_id = ${q(user)};`);
}

// Profile: one row per user, upserted.
{
  const p = { ...data.profile } as Row;
  delete p.user_id;
  const cols = Object.keys(p);
  out.push(`insert into public.profiles (user_id, ${cols.join(', ')}) values (${q(user)}, ${cols.map((c) => literal('profiles', c, p[c])).join(', ')})`);
  out.push(`  on conflict (user_id) do update set ${cols.map((c) => `${c} = excluded.${c}`).join(', ')};`);
}

const goalMeasure: [string, string][] = [];
for (const [key, table] of ORDER) {
  const rows = (data[key] as Row[] | undefined) ?? [];
  if (!rows.length) continue;
  out.push(`\n-- ${table} (${rows.length})`);
  for (const raw of rows) {
    const r: Row = { ...raw };
    delete r.user_id;
    for (const g of GONE[table] ?? []) delete r[g];
    if (table === 'goals' && r.measurement_type_id) {
      // Goals and their measurement types point at each other: link after both exist.
      goalMeasure.push([String(r.id), String(r.measurement_type_id)]);
      r.measurement_type_id = null;
    }
    if (table === 'goal_ideas' && r.status === 'selected') r.status = 'backlog';
    const cols = Object.keys(r).filter((c) => r[c] !== undefined);
    out.push(`insert into public.${table} (user_id, ${cols.join(', ')}) values (${q(user)}, ${cols.map((c) => literal(table, c, r[c])).join(', ')}) on conflict (id) do nothing;`);
  }
}
if (goalMeasure.length) {
  out.push('\n-- goals → their measurement');
  for (const [g, m] of goalMeasure) out.push(`update public.goals set measurement_type_id = ${q(m)} where id = ${q(g)} and user_id = ${q(user)};`);
}
out.push('commit;');
process.stdout.write(out.join('\n') + '\n');
