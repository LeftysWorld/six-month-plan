// Bundles the workout coach's door (apps/web/api-src/workout-agent.ts and the shared code it uses)
// into one plain JavaScript file Vercel runs as a server function: apps/web/api/workout-agent/[route].js.
// Run after changing api-src/ or supabase/functions/_shared/: `node apps/web/scripts/build-agent-api.mjs`.
// The test apps/web/test/agent-api.test.ts fails while the bundle is out of date.
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const { build } = await import(process.env.ESBUILD ?? 'esbuild');

export async function bundleAgentApi(write = true) {
  const result = await build({
    entryPoints: [resolve(here, '../api-src/workout-agent.ts')],
    bundle: true,
    platform: 'node',
    format: 'esm',
    target: 'node20',
    external: ['@supabase/supabase-js'],
    outfile: resolve(here, '../api/workout-agent/[route].js'),
    banner: { js: '// Generated by apps/web/scripts/build-agent-api.mjs from apps/web/api-src/workout-agent.ts. Do not edit.' },
    legalComments: 'none',
    absWorkingDir: resolve(here, '../../..'),
    write,
    logLevel: 'error',
  });
  return result.outputFiles?.[0]?.text ?? null;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await bundleAgentApi(true);
  console.log('wrote apps/web/api/workout-agent/[route].js');
}
