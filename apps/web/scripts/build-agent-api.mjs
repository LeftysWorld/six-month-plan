// Bundles the workout coach's door (apps/web/api-src/workout-agent.ts and the shared code it uses)
// into one plain JavaScript file Vercel runs as a server function: apps/web/api/workout-agent/[route].js.
// Run after changing api-src/ or supabase/functions/_shared/: `node apps/web/scripts/build-agent-api.mjs`.
// The test apps/web/test/agent-api.test.ts fails while the bundle is out of date.
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const { build } = await import(process.env.ESBUILD ?? 'esbuild');

/** The app's server functions: api-src/<name>.ts → api/<name>/[route].js. */
export const API_ENTRIES = ['workout-agent', 'calendar'];

export async function bundleAgentApi(write = true, name = 'workout-agent') {
  const result = await build({
    entryPoints: [resolve(here, `../api-src/${name}.ts`)],
    bundle: true,
    platform: 'node',
    format: 'esm',
    target: 'node20',
    external: ['@supabase/supabase-js'],
    outfile: resolve(here, `../api/${name}/[route].js`),
    banner: { js: `// Generated by apps/web/scripts/build-agent-api.mjs from apps/web/api-src/${name}.ts. Do not edit.` },
    legalComments: 'none',
    absWorkingDir: resolve(here, '../../..'),
    write,
    logLevel: 'error',
  });
  return result.outputFiles?.[0]?.text ?? null;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  for (const name of API_ENTRIES) {
    await bundleAgentApi(true, name);
    console.log(`wrote apps/web/api/${name}/[route].js`);
  }
}
